import { execFileSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const revision = '23fb567d2a430db8eda47ff4011abccd8030ae5a';
const checkout = process.argv[2];
if (!checkout) throw new Error('Usage: node scripts/vendor-mrrp.mjs /path/to/mrrp');
const git = (...args) => execFileSync('git', ['-C', checkout, ...args], { encoding: 'utf8' });
if (git('rev-parse', 'HEAD').trim() !== revision || git('status', '--porcelain')) {
  throw new Error('Use a clean mrrp checkout at ' + revision);
}

const sourceDir = resolve(checkout, 'packages/web/src');
const patch = fileURLToPath(new URL('./patches/mrrp-room.patch', import.meta.url));

async function readRoomSource() {
  const temporary = await mkdtemp(join(tmpdir(), 'portfolio-mrrp-'));
  try {
    const cat = join(temporary, 'Cat.tsx');
    await writeFile(cat, await readFile(join(sourceDir, 'Cat.tsx')));
    execFileSync('git', ['apply', patch], { cwd: temporary });
    return await readFile(cat, 'utf8');
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}

const roomSource = await readRoomSource();
const result = await build({
  stdin: {
    contents: "export { Cat } from './Cat.tsx';",
    resolveDir: sourceDir,
  },
  alias: { '@mrrp/shared': resolve(checkout, 'packages/shared/src/index.ts') },
  bundle: true,
  write: false,
  format: 'iife',
  globalName: 'renderer',
  minify: true,
  legalComments: 'none',
  target: 'es2022',
  jsx: 'automatic',
  plugins: [
    {
      name: 'portfolio-room',
      setup(plugin) {
        plugin.onLoad({ filter: /\/Cat\.tsx$/ }, () => ({
          contents: roomSource,
          loader: 'tsx',
          resolveDir: sourceDir,
        }));
        plugin.onResolve({ filter: /^(react(?:\/jsx-runtime)?|\.\/sound\.js)$/ }, ({ path }) => ({
          path,
          namespace: 'room-bridge',
        }));
        plugin.onLoad({ filter: /.*/, namespace: 'room-bridge' }, ({ path }) => ({
          contents:
            path === './sound.js'
              ? 'export function play() {} export function playPianoNote() {} export function setVoice() {}'
              : 'module.exports = ' + (path === 'react' ? 'React' : 'jsxRuntime'),
        }));
        plugin.onLoad({ filter: /\/constellation\.ts$/ }, async ({ path }) => ({
          contents: (await readFile(path, 'utf8')).replaceAll('= localStorage', '= roomMemory'),
          loader: 'ts',
        }));
      },
    },
  ],
});
const vendor = new URL('../src/ui/showcase/mrrp/', import.meta.url);
const code = result.outputFiles[0].text.trim();
await writeFile(
  new URL('renderer.js', vendor),
  '// Generated by scripts/vendor-mrrp.mjs from mrrp ' +
    revision +
    ' with the portfolio room patch.\n' +
    '// MIT attribution in public/projects/mrrp-license.txt.\n' +
    "import * as React from 'react';\nimport * as jsxRuntime from 'react/jsx-runtime';\n\n" +
    '// prettier-ignore\n' +
    `export const Cat = (() => { const memory = new Map(); const roomMemory = { getItem: (key) => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) }; ${code} return renderer.Cat; })();\n`,
);
await writeFile(
  new URL('../public/projects/mrrp-license.txt', import.meta.url),
  git('show', 'HEAD:LICENSE'),
);
